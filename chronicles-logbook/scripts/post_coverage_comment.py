"""Posts (or updates) a coverage summary comment on a Gitea pull request,
including per-file breakdown tables generated by coverage_table.py.

Reads coverage percentages, table file paths, and PR context from
environment variables set by the CI workflow, then calls the Gitea API
directly. Gitea Actions exposes GitHub-compatible env vars/context
(GITHUB_TOKEN, github.api_url, github.repository) even though it isn't
GitHub, which is what this relies on. Uses only the standard library so
no extra pip install step is needed.
"""

import json
import os
import sys
import urllib.request

API_URL = os.environ["GITEA_API_URL"].rstrip("/")
TOKEN = os.environ["GITEA_TOKEN"]
REPO = os.environ["GITEA_REPOSITORY"]
PR_NUMBER = os.environ["PR_NUMBER"]
BACKEND_COVERAGE = os.environ.get("BACKEND_COVERAGE", "0")
FRONTEND_COVERAGE = os.environ.get("FRONTEND_COVERAGE", "0")
BACKEND_TABLE_PATH = os.environ.get("BACKEND_TABLE_PATH", "")
FRONTEND_TABLE_PATH = os.environ.get("FRONTEND_TABLE_PATH", "")

# Marker used to find and update our own comment on re-runs, instead of
# spamming a new comment on every push to the PR.
COMMENT_MARKER = "<!-- coverage-report -->"


def api_request(method: str, path: str, body: dict | None = None) -> dict:
    url = f"{API_URL}{path}"
    data = json.dumps(body).encode() if body is not None else None
    request = urllib.request.Request(url, data=data, method=method)
    request.add_header("Authorization", f"token {TOKEN}")
    request.add_header("Content-Type", "application/json")
    with urllib.request.urlopen(request) as response:
        raw = response.read()
        return json.loads(raw) if raw else {}


def find_existing_comment_id() -> int | None:
    comments = api_request("GET", f"/repos/{REPO}/issues/{PR_NUMBER}/comments")
    for comment in comments:
        if COMMENT_MARKER in comment.get("body", ""):
            return comment["id"]
    return None


def read_table(path: str) -> str:
    if not path or not os.path.exists(path):
        return "_No data._\n"
    with open(path, encoding="utf-8") as f:
        return f.read()


def build_comment_body() -> str:
    backend_table = read_table(BACKEND_TABLE_PATH)
    frontend_table = read_table(FRONTEND_TABLE_PATH)
    return (
        f"{COMMENT_MARKER}\n"
        "### Coverage Report\n\n"
        "| Component | Line Coverage |\n"
        "|---|---|\n"
        f"| Backend  | {BACKEND_COVERAGE}% |\n"
        f"| Frontend | {FRONTEND_COVERAGE}% |\n\n"
        "<details>\n<summary>Backend — per-file breakdown</summary>\n\n"
        f"{backend_table}\n</details>\n\n"
        "<details>\n<summary>Frontend — per-file breakdown</summary>\n\n"
        f"{frontend_table}\n</details>\n"
    )


def main() -> None:
    body = build_comment_body()
    existing_id = find_existing_comment_id()
    if existing_id is not None:
        api_request(
            "PATCH",
            f"/repos/{REPO}/issues/comments/{existing_id}",
            {"body": body},
        )
    else:
        api_request(
            "POST",
            f"/repos/{REPO}/issues/{PR_NUMBER}/comments",
            {"body": body},
        )


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:  # noqa: BLE001
        # A failed comment post shouldn't fail the whole CI run over
        # something cosmetic — log it and exit clean.
        print(f"Failed to post coverage comment: {exc}", file=sys.stderr)
        sys.exit(0)